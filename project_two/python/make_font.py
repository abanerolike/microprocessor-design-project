"""Font for the VGA text: 48 characters, 5 x 7 dots in an 8 x 8 cell (columns 1..5, rows 0..6).

The glyphs are drawn here by hand. The script prints the VHDL constant for src/text.vhd: one line per
character, eight row bytes, bit 7 = left column. The character set string must match CHARS in text.vhd.
"""
CHARS = " 0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZ.:()-=%zpus"
ART = """
..... .###. ..#.. .###. ##### ...#. ##### ..##. ##### .###. .###.
..... #...# .##.. #...# ...#. ..##. #.... .#... ....# #...# #...#
..... #..## ..#.. ....# ..#.. .#.#. ####. #.... ...#. #...# #...#
..... #.#.# ..#.. ...#. ...#. #..#. ....# ####. ..#.. .###. .####
..... ##..# ..#.. ..#.. ....# ##### ....# #...# .#... #...# ....#
..... #...# ..#.. .#... #...# ...#. #...# #...# .#... #...# ...#.
..... .###. .###. ##### .###. ...#. .###. .###. .#... .###. .##..

.###. ####. .###. ###.. ##### ##### .###. #...# .###. ..### #...# #.... #...#
#...# #...# #...# #..#. #.... #.... #...# #...# ..#.. ...#. #..#. #.... ##.##
#...# #...# #.... #...# #.... #.... #.... #...# ..#.. ...#. #.#.. #.... #.#.#
##### ####. #.... #...# ####. ####. #.### ##### ..#.. ...#. ##... #.... #.#.#
#...# #...# #.... #...# #.... #.... #...# #...# ..#.. ...#. #.#.. #.... #...#
#...# #...# #...# #..#. #.... #.... #...# #...# ..#.. #..#. #..#. #.... #...#
#...# ####. .###. ###.. ##### #.... .#### #...# .###. .##.. #...# ##### #...#

#...# .###. ####. .###. ####. .#### ##### #...# #...# #...# #...# #...# #####
#...# #...# #...# #...# #...# #.... ..#.. #...# #...# #...# #...# #...# ....#
##..# #...# #...# #...# #...# #.... ..#.. #...# #...# #...# .#.#. .#.#. ...#.
#.#.# #...# ####. #...# ####. .###. ..#.. #...# #...# #.#.# ..#.. ..#.. ..#..
#..## #...# #.... #.#.# #.#.. ....# ..#.. #...# #...# #.#.# .#.#. ..#.. .#...
#...# #...# #.... #..#. #..#. ....# ..#.. #...# .#.#. #.#.# #...# ..#.. #....
#...# .###. #.... .##.# #...# ####. ..#.. .###. ..#.. .#.#. #...# ..#.. #####

..... ..... ...#. .#... ..... ..... ##... ..... ..... ..... .....
..... .##.. ..#.. ..#.. ..... ..... ##..# ..... ..... ..... .....
..... .##.. .#... ...#. ..... ##### ...#. ##### ####. #...# .####
..... ..... .#... ...#. ##### ..... ..#.. ...#. #...# #...# #....
..... .##.. .#... ...#. ..... ##### .#... ..#.. ####. #...# .###.
.##.. .##.. ..#.. ..#.. ..... ..... #..## .#... #.... #..## ....#
.##.. ..... ...#. .#... ..... ..... ...## ##### #.... .##.# ####.
"""

blocks = [b.strip().splitlines() for b in ART.strip().split("\n\n")]
glyphs = []
for rows in blocks:
    cells = [r.split() for r in rows]
    for c in range(len(cells[0])):
        glyphs.append([int("0" + cells[r][c].replace("#", "1").replace(".", "0") + "00", 2) for r in range(7)] + [0])
assert len(glyphs) == len(CHARS), (len(glyphs), len(CHARS))
for ch, g in zip(CHARS, glyphs):
    print("\t\t" + ", ".join(f'x"{v:02X}"' for v in g) + ",   -- " + repr(ch))
